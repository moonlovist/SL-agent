from typing import Dict, Any

from ..core.base_agent import BaseAgent
from ..core.state import ExpertState


class ReportWriter(BaseAgent):
    """
    Expert report generation Agent.

    Converts the reasoning process into a final report.

    Does not make new judgement.

    Only summarizes:
    - observations;
    - hypotheses;
    - evidence;
    - contradictions;
    - confidence calibration;
    - audit results.
    """


    def __init__(self):
        super().__init__("ReportWriter")


    def run(
        self,
        state: ExpertState
    ) -> ExpertState:


        self.log(
            "生成专家分析报告"
        )


        # Keep the confidence judgement
        # generated by ConfidenceAgent.

        confidence_result = (
            state.final_decision
            if state.final_decision
            else {}
        )


        report = {


            "observations":
                state.observations,


            "hypotheses":
                state.hypotheses,


            "evidence":
                state.evidence,


            "contradictions":
                state.contradictions,


            "confidence_assessment":
                confidence_result,


            "audit":
                state.audit_result,


            "final_statement":
                (
                    "Expert judgement generated "
                    "from evidence balance, "
                    "contradiction analysis, "
                    "and confidence calibration."
                )

        }


        state.final_decision = report


        self.record_reasoning(
            state,

            action="report_generation",

            content=report
        )


        return state